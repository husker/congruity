"""Layer 4b — produce the markdown digest from ranked bridges."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path


def render_digest(
    scored_bridges: list[dict],
    run_meta: dict,
    top_n: int = 10,
    confidence_floor: int = 7,
) -> str:
    """Render the top-N bridges into markdown."""
    eligible = [
        b for b in scored_bridges
        if b.get("status") == "complete"
        and b.get("citation_check", {}).get("passes", False)
        and (b.get("confidence") or 0) >= confidence_floor
    ]
    eligible.sort(key=lambda b: -b.get("score", 0.0))
    top = eligible[:top_n]

    lines = [
        f"# Discovery digest — {datetime.now(timezone.utc).strftime('%Y-%m-%d')}",
        "",
        "Generated by congruity v1 batch pipeline.",
        "",
        "## Run summary",
        "",
        f"- Topics in pool: **{run_meta.get('topics_count', '?')}**",
        f"- Pairs filtered (Layer 2): **{run_meta.get('pairs_total', '?')}**",
        f"- Pairs passing Swanson-shape gate: **{run_meta.get('pairs_passing', '?')}**",
        f"- Pairs processed through Codex (Layer 3): **{run_meta.get('pairs_processed', '?')}**",
        f"- Discoveries with grounded citations: **{len([b for b in scored_bridges if b.get('citation_check', {}).get('passes')])}**",
        f"- Discoveries meeting confidence floor (≥{confidence_floor}/10): **{len(eligible)}**",
        f"- Confabulations caught and filtered: **{sum(1 for b in scored_bridges if (b.get('citation_check') or {}).get('confabulated', 0))}**",
        "",
        f"## Top {len(top)} bridges",
        "",
    ]

    if not top:
        lines.append("_No bridges met the inclusion criteria. See full results in `data/pipeline/runs/`._")
    else:
        for i, b in enumerate(top, 1):
            check = b.get("citation_check") or {}
            sb = b.get("score_breakdown") or {}
            lines.extend([
                f"### {i}. {b['a_name']} ↔ {b['b_name']}",
                "",
                f"- **Score:** {b.get('score', 0):.3f}",
                f"- **Codex confidence:** {b.get('confidence', '?')}/10",
                f"- **Citation grounding:** {check.get('grounded', 0)}/{check.get('citations_extracted', 0)} verified",
                f"- **Corpus size:** A={b.get('side_a_count')}, B={b.get('side_b_count')}",
                "",
                "**Bridge claim and mechanism (from Codex):**",
                "",
            ])
            response_path = b.get("response_path")
            if response_path:
                try:
                    excerpt = Path(response_path).read_text()
                    lines.append("```")
                    lines.append(excerpt.strip()[:3000])
                    if len(excerpt) > 3000:
                        lines.append(f"\n... (truncated; full response at {response_path})")
                    lines.append("```")
                except OSError:
                    lines.append(f"_Response file unreadable: {response_path}_")
            lines.append("")
            if sb:
                lines.append("**Score breakdown:**")
                lines.append("")
                for k, v in sb.items():
                    w = v["weight"]
                    val = v["value"]
                    lines.append(f"- {k}: {val:.2f} × {w:.2f} = {val * w:.3f}")
                lines.append("")
            lines.append(f"_Full artifacts: `data/pipeline/runs/{b['pair_id']}/`_")
            lines.append("")
            lines.append("---")
            lines.append("")

    lines.extend([
        "## All ranked discoveries",
        "",
        "| Rank | Score | Conf | Grounded | Pair |",
        "|---|---|---|---|---|",
    ])
    all_eligible = sorted(
        [b for b in scored_bridges if b.get("status") == "complete"],
        key=lambda b: -b.get("score", 0.0),
    )
    for i, b in enumerate(all_eligible, 1):
        c = b.get("citation_check") or {}
        grounded = "✓" if c.get("passes") else "✗"
        lines.append(
            f"| {i} | {b.get('score', 0):.3f} | {b.get('confidence', '?')}/10 | "
            f"{grounded} | {b['a_name']} ↔ {b['b_name']} |"
        )
    lines.append("")

    skipped = [b for b in scored_bridges if b.get("status") != "complete"]
    if skipped:
        lines.append("## Skipped / failed pairs")
        lines.append("")
        for b in skipped:
            lines.append(f"- {b['a_name']} ↔ {b['b_name']}: {b.get('status')}")
        lines.append("")

    return "\n".join(lines)


def write_digest(content: str, out_path: Path) -> Path:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content)
    return out_path
